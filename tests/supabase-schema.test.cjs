const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { PGlite } = require('@electric-sql/pglite');
const A = '11111111-1111-4111-8111-111111111111';
const B = '22222222-2222-4222-8222-222222222222';

test('PostgreSQL schema enforces owner isolation, server-only writes, durable quotas and fenced leases', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema auth to authenticated; grant execute on function auth.uid() to authenticated;
      insert into auth.users values ('${A}'), ('${B}');`);
    await db.exec(fs.readFileSync(require('node:path').join(__dirname, '../supabase/migrations/202610110001_workspace.sql'), 'utf8'));
    await db.exec(fs.readFileSync(require('node:path').join(__dirname, '../supabase/migrations/202610110002_atomic_deal_updates.sql'), 'utf8'));
    await db.exec(fs.readFileSync(require('node:path').join(__dirname, '../supabase/migrations/202610120001_contract_drafts.sql'), 'utf8'));
    await db.exec(`insert into public.creatorpay_workspaces(owner_id) values ('${A}'), ('${B}');
      insert into public.creatorpay_deals(id,owner_id,body) values ('deal-a','${A}','{"id":"deal-a"}'),('deal-b','${B}','{"id":"deal-b"}');
      set role authenticated; set request.jwt.claim.sub = '${A}';`);
    assert.deepEqual((await db.query('select id from public.creatorpay_deals')).rows, [{ id: 'deal-a' }]);
    assert.equal((await db.query(`select * from public.creatorpay_workspaces where owner_id='${B}'`)).rows.length, 0);
    await assert.rejects(db.exec(`update public.creatorpay_deals set body='{"id":"deal-a","status":"payouts_completed"}' where id='deal-a'`), /permission denied/);
    await assert.rejects(db.exec(`select public.creatorpay_reserve_analysis('${A}')`), /permission denied/);
    await assert.rejects(db.query('select public.creatorpay_save_draft($1,0,$2)',[A,JSON.stringify({prompt:'forbidden',useTeamRules:false})]), /permission denied/);
    await db.exec('reset role; set role anon;');
    await assert.rejects(db.query('select * from public.creatorpay_deals'), /permission denied/);
    await db.exec('reset role; set role service_role;');
    await db.query('select public.creatorpay_reserve_analysis($1)', [A]);
    await assert.rejects(db.query('select public.creatorpay_reserve_analysis($1)', [A]), /Wait 10 seconds/);
    assert.equal((await db.query("select count from public.creatorpay_usage where bucket='global'")).rows[0].count, 1);
    await db.exec(`update public.creatorpay_usage set count=10,last_at=now()-interval '1 minute' where owner_id='${A}'`);
    await assert.rejects(db.query('select public.creatorpay_reserve_analysis($1)', [A]), /Daily account limit/);
    await db.exec("update public.creatorpay_usage set count=100 where bucket='global'");
    await assert.rejects(db.query('select public.creatorpay_reserve_analysis($1)', [B]), /Daily server budget/);
    assert.equal((await db.query(`select * from public.creatorpay_usage where owner_id='${B}'`)).rows.length, 0, 'failed reservation must roll back');
    await assert.rejects(db.query('select public.creatorpay_acquire_job($1,$2,$3)', ['invoice-a', 'deal-a', B]), /Deal access denied/);
    const lease = (await db.query('select public.creatorpay_acquire_job($1,$2,$3) as result', ['invoice-a', 'deal-a', A])).rows[0].result;
    await assert.rejects(db.query('select public.creatorpay_acquire_job($1,$2,$3)', ['invoice-a', 'deal-a', A]), /already running/);
    await db.query('select public.creatorpay_checkpoint_job($1,$2,$3)', ['invoice-a', lease.token, 'INV-TEST']);
    await assert.rejects(db.query('select public.creatorpay_checkpoint_job($1,$2,$3)', ['invoice-a', lease.token, 'INV-OTHER']), /mismatch/);
    await db.exec("update public.creatorpay_jobs set lease_until=now()-interval '1 second'");
    const recovered = (await db.query('select public.creatorpay_acquire_job($1,$2,$3) as result', ['invoice-a', 'deal-a', A])).rows[0].result;
    assert.equal(recovered.invoiceId, 'INV-TEST');
    assert.notEqual(recovered.token, lease.token);
    await db.query('select public.creatorpay_release_job($1,$2)', ['invoice-a', lease.token]);
    await assert.rejects(db.query('select public.creatorpay_acquire_job($1,$2,$3)', ['invoice-a', 'deal-a', A]), /already running/);
    await assert.rejects(db.query('select public.creatorpay_checkpoint_job($1,$2,$3)', ['invoice-a', lease.token, 'INV-TEST']), /expired/);
    await db.query('select public.creatorpay_release_job($1,$2)', ['invoice-a', recovered.token]);
    const commit = (owner, revision, body, invoice = null, event = null, eventInvoice = null) => db.query('select public.creatorpay_commit_deal($1,$2,$3,$4,$5,$6,$7,$8) as result', [owner,'deal-a',revision,JSON.stringify(body),invoice ? JSON.stringify(invoice):null,'[]',event,eventInvoice]);
    await assert.rejects(commit(B,0,{id:'deal-a'}), /access denied/);
    await commit(A,0,{id:'deal-a',status:'invoiced'},{id:'INV-A',milestoneId:'m1',merchantEmail:'merchant@example.com'});
    await assert.rejects(commit(A,0,{id:'deal-a',status:'stale'}), /changed/);
    await assert.rejects(commit(A,1,{id:'deal-a',status:'bad'},null,'event-bad','INV-WRONG'), /Untracked/);
    assert.equal((await db.query('select revision from public.creatorpay_deals where id=$1',['deal-a'])).rows[0].revision,1);
    await commit(A,1,{id:'deal-a',status:'paid'},null,'event-a','INV-A');
    const duplicate=(await commit(A,1,{id:'deal-a',status:'regression'},null,'event-a','INV-A')).rows[0].result;
    assert.equal(duplicate.duplicate,true);assert.equal(duplicate.body.status,'paid');
    assert.equal((await db.query("select body->>'status' as status from public.creatorpay_invoice_links where invoice_id='INV-A'")).rows[0].status,'PAID');
  } finally { await db.close(); }
});
